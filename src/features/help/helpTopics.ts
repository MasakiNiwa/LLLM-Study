export const HELP_TOPICS: HelpTopic[] = [...HELP_STEPS, ...EXTRA_TOPICS];

/** 文字の 2 文字ずつの組（日本語でも単語に分けずに比べられる）。ひらがなだけの組は除く */
function bigrams(text: string): Set<string> {
  const t = text
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[\s、。・「」（）()!?！？,.]/g, '');
  const out = new Set<string>();
  for (let i = 0; i < t.length - 1; i++) {
    const g = t.slice(i, i + 2);
    if (!/^[\u3040-\u309f]{2}$/.test(g)) out.add(g);
  }
  return out;
}

const INDEX = HELP_TOPICS.map((t) => ({
  topic: t,
  title: bigrams(t.title),
  body: bigrams(t.body),
}));

/**
 * 質問に関係しそうなヘルプの項目を選ぶ（プログラムの役目）。
 * 2 文字ずつの組がどれだけ重なるかで点を付け、見出しに含まれるものを重く数える。
 */
export function searchHelp(query: string, limit = 3): HelpTopic[] {
  const q = bigrams(query);
  if (q.size === 0) return [];
  return INDEX.map(({ topic, title, body }) => {
    let score = 0;
    for (const g of q) {
      if (title.has(g)) score += 3;
      if (body.has(g)) score += 1;
    }
    return { topic, score };
  })
    .filter((r) => r.score >= 2)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((r) => r.topic);
}

/** AI に使い方を聞くときに、質問に添えるヘルプの抜粋と指示 */
export function helpContext(question: string): string {
  const topics = searchHelp(question);
  const found = topics.length > 0 ? topics : HELP_TOPICS.filter((t) => t.title === '画面の構成');
  return [
    '<app_help>',
    ...found.map((t) => `## ${t.title}\n${t.body}`),
    '</app_help>',
    'ユーザーはアプリ「LLLM Study」の使い方を質問しています。上の <app_help> はアプリのヘルプから、質問に関係しそうな部分をアプリが選んだものです。',
    'この内容だけをもとに、どの画面で何を押せばよいかを短く具体的に答えてください。ヘルプに書かれていないことは推測で答えず、「ヘルプに見当たりませんでした」と伝えて、ヘルプ画面（右上の「？」）を見るよう案内してください。',
  ].join('\n');
}
